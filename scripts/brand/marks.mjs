/**
 * Знак «Мира холода и тепла». Три варианта, один выбран.
 *
 * Правила (CLAUDE.md, SPEC §11.4):
 *   — не больше двух цветов из токенов, никаких градиентов и теней:
 *     на 16 px градиент превращается в кашу, а тень — в грязь;
 *   — синий и красный не встречаются вместе, их разводит сезон,
 *     поэтому цветной элемент ровно один и красится в --c-accent;
 *   — сетка 32×32, все опорные точки кратны 0.5, толщины кратны 0.5:
 *     при делении на 2 (16 px) штрихи остаются на пиксельной сетке.
 */

/** Палитра — копия токенов из src/styles/tokens.css. */
export const palette = {
  dial: '#F4F6F7',
  ink: '#191E23',
  low: '#0B5AA6',
  high: '#B3261E',
};

/**
 * Вариант A. «Контур».
 *
 * Трасса проходит кадр насквозь: два отвода, вход сверху, выход снизу.
 * Труба одна и та же — меняется только то, что по ней идёт, поэтому
 * половины покрашены по-разному и стык ровно в середине. Холод и тепло
 * не рядом, а в одном объекте: это буквально подача и обратка.
 */
const kontur = ({ ink, accent }) => `
  <g fill="none" stroke-width="6" stroke-linecap="butt">
    <path d="M9.5 0v11.5a4.5 4.5 0 0 0 4.5 4.5H16" stroke="${ink}"/>
    <path d="M16 16h2a4.5 4.5 0 0 1 4.5 4.5V32" stroke="${accent}"/>
  </g>`;

/**
 * Вариант B. «Лимб».
 *
 * Манометрический коллектор — прибор, который мастер вешает на блок первым
 * делом, и метафора всей дизайн-системы (SPEC §11). Одна шкала: на одном
 * конце холод, на другом тепло, стрелка живёт между ними. Дуга со стопорами
 * графитовая, стрелка цветная.
 */
const limb = ({ ink, accent }) => `
  <g fill="none" stroke-linecap="butt">
    <path d="M5.5 21.5a10.5 10.5 0 0 1 21 0" stroke="${ink}" stroke-width="4.5"/>
    <path d="M5.5 21.5v3.5M26.5 21.5v3.5" stroke="${ink}" stroke-width="4.5"/>
    <path d="M16 21.5 23.5 14" stroke="${accent}" stroke-width="4.5"/>
  </g>`;

/**
 * Вариант C. «Трасса».
 *
 * Медная трасса в разрезе: толстая газовая линия и тонкая жидкостная,
 * стянутые в один жгут. По одному маршруту едут и холод, и тепло —
 * буквально один объект. Газовая графитовая, жидкостная цветная.
 */
const trassa = ({ ink, accent }) => `
  <g>
    <circle cx="12" cy="16" r="6.75" fill="none" stroke="${ink}" stroke-width="4.5"/>
    <circle cx="25.5" cy="16" r="3.25" fill="${accent}"/>
  </g>`;

export const marks = { kontur, limb, trassa };

/**
 * Выбранный знак. Переключается одним словом: 'kontur' | 'limb' | 'trassa'.
 * После правки — npm run brand.
 */
export const MARK = 'kontur';

/**
 * Знак целиком: подложка плюс рисунок.
 *
 * bleed = true — подложка во весь квадрат без скругления (apple-touch-icon:
 * iOS скругляет сам, своё скругление получает вторую рамку).
 *
 * Трубка «Контура» намеренно уходит за верхний и нижний край, поэтому рисунок
 * подрезается по подложке: иначе на скруглённых углах торчат хвосты.
 */
export function markSvg({
  name = MARK,
  accent,
  size = 32,
  bleed = false,
  bg = palette.dial,
  ink = palette.ink,
} = {}) {
  const draw = marks[name];
  if (!draw) throw new Error(`[brand] Неизвестный знак «${name}». Есть: ${Object.keys(marks).join(', ')}`);
  const shape = bleed ? '<rect width="32" height="32"/>' : '<rect width="32" height="32" rx="6"/>';
  const id = `plate-${name}`;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="${size}" height="${size}" role="img" aria-label="Мир холода и тепла">` +
    `<defs><clipPath id="${id}">${shape}</clipPath></defs>` +
    `<g clip-path="url(#${id})"><g fill="${bg}">${shape}</g>${draw({ ink, accent })}</g>` +
    `</svg>`
  );
}
